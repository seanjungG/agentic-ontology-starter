def build_docs(L: Ledger, lang: str) -> List[Dict[str, str]]:
    docs: List[Dict[str, str]] = []
    core_dir = CORE / lang / "docs"
    core_cat = json.loads((CORE / lang / "catalog.json").read_text(encoding="utf-8"))["docs"]
    for c in core_cat:   # the 4 hands-on documents stay in the pack unchanged
        docs.append({"doc_id": c["doc_id"], "title": c["title"], "kind": "core", "file": "core_" + c["file"], "text": (core_dir / c["file"]).read_text(encoding="utf-8")})
    for prog in PROGRAMS:
        for line in LINE_KEYS:
            title, text = guide(L, prog, line, lang)
            docs.append({"doc_id": gid(prog, line), "title": title, "kind": "guide", "file": f"guide_{prog.lower()}_{line.lower()}.md", "text": text})
    for m in NOTICE_MONTHS:
        title, text = notice(L, m, lang)
        docs.append({"doc_id": nid(m), "title": title, "kind": "notice", "file": f"notice_2026_{m:02d}.md", "text": text})
    for doc_id, fn in (("ADDENDUM-EX-01", addendum1), ("ADDENDUM-EX-02", addendum2), ("GLOSSARY-01", glossary)):
        title, text = fn(lang)
        docs.append({"doc_id": doc_id, "title": title, "kind": "addendum" if doc_id.startswith("ADD") else "glossary", "file": doc_id.lower().replace("-", "_") + ".md", "text": text})
    for line in LINE_KEYS:
        for as_of in (dt.date(2026, 3, 15), dt.date(2026, 6, 15)):
            doc_id, title, text = faq(L, line, as_of, lang)
            docs.append({"doc_id": doc_id, "title": title, "kind": "faq", "file": doc_id.lower().replace("-", "_") + ".md", "text": text})
        doc_id, title, text = archive(L, line, lang)
        docs.append({"doc_id": doc_id, "title": title, "kind": "archive", "file": doc_id.lower().replace("-", "_") + ".md", "text": text})
    for m in (4, 5, 6, 7, 8, 9):
        doc_id, title, text = memo(L, m, lang)
        docs.append({"doc_id": doc_id, "title": title, "kind": "memo", "file": doc_id.lower().replace("-", "_") + ".md", "text": text})
    return docs


