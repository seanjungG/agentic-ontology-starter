_DIGIT_BATCHIM = {"0": True, "1": True, "3": True, "6": True, "7": True, "8": True, "2": False, "4": False, "5": False, "9": False}
_DIGIT_RIEUL = {"1", "7", "8"}


def josa(word: str, pair: str) -> str:
    """Korean particle by the final sound of ``word``: pair is one of 을를 · 이가 · 은는 · 으로 (으로/로)."""
    w = re.sub(r"[\s*`)\]]+$", "", word)
    ch = w[-1] if w else ""
    if "가" <= ch <= "힣":
        jong = (ord(ch) - 0xAC00) % 28
        batchim, rieul = jong != 0, jong == 8
    elif ch == "%":
        batchim, rieul = False, False      # 퍼센트
    elif ch in _DIGIT_BATCHIM:
        batchim, rieul = _DIGIT_BATCHIM[ch], ch in _DIGIT_RIEUL
    else:
        batchim, rieul = False, False
    if pair == "으로":
        return word + ("로" if (not batchim or rieul) else "으로")
    return word + (pair[0] if batchim else pair[1])


