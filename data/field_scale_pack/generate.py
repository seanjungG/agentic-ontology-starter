def _nice(unit: str, v: float) -> int:
    if unit == "pct":
        return int(round(v / 5.0) * 5)
    if unit == "days":
        return int(round(v / 15.0) * 15)
    step = 10000 if v >= 100000 else (5000 if v >= 10000 else 500)
    return max(step, int(round(v / step) * step))


def clawback(L: Ledger, line: str, activated: dt.date, bonus: int, elapsed: int) -> Tuple[int, str]:
    """(amount, mode) — the rule in force on the activation date."""
    if elapsed >= 180:
        return 0, "none"
    pro = CLAWBACK_PRORATA.get(line)
    if pro and activated >= pro and elapsed >= 90:
        return int(round(bonus * (180 - elapsed) / 180.0)), "prorata"
    return bonus, "full"


