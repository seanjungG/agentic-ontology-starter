# ------------------------------------------------------------------------------------------------- ledger
class Ledger:
    """Base values + dated amendments. ``value(prog, line, param, date)`` is the single source of every number."""

    def __init__(self) -> None:
        self.changes: Dict[Tuple[str, str, str], List[Dict[str, Any]]] = {}
        self.notices: Dict[int, List[Dict[str, Any]]] = {m: [] for m in NOTICE_MONTHS}
        self._build()

    def base(self, prog: str, line: str, param: str) -> int:
        return BASE[prog][param][LINE_KEYS.index(line)]

    def value(self, prog: str, line: str, param: str, on: dt.date) -> int:
        v = self.base(prog, line, param)
        for c in self.changes.get((prog, line, param), []):
            if c["effective"] <= on:
                v = c["new"]
        return v

    def history(self, prog: str, line: str, param: str) -> List[Tuple[dt.date, int, str]]:
        out = [(D0, self.base(prog, line, param), gid(prog, line))]
        out += [(c["effective"], c["new"], nid(c["month"])) for c in self.changes.get((prog, line, param), [])]
        return out

    def _step(self, rng: random.Random, unit: str, old: int) -> int:
        if unit == "pct":
            return old + rng.choice([5, 5, 10, -5])
        if unit == "days":
            return old + rng.choice([30, 30, 15, -15])
        if old >= 100000:
            return old + rng.choice([10000, 20000, 20000, 30000, 50000, -10000, -20000])
        if old >= 10000:
            return old + rng.choice([5000, 10000, 10000, -5000])
        return old + rng.choice([500, 500, 1000, -500])

    def _valid(self, prog: str, line: str, param: str, new: int, on: dt.date) -> bool:
        unit = PARAMS[prog][param][0]
        if new <= 0 or (unit == "pct" and not 5 <= new <= 95) or (unit == "days" and not 30 <= new <= 240):
            return False
        cur = {p: self.value(prog, line, p, on) for p in PARAMS[prog]}
        cur[param] = new
        if any(cur[a] >= cur[b] for a, b in ORDERED.get(prog, [])):
            return False
        return not (prog == "INSUR" and cur["damage_deduct"] * 3 > cur["damage_cap"])

    def _build(self) -> None:
        rng = random.Random(SEED)
        keys = [(p, ln, k) for p in PARAMS for ln in LINE_KEYS for k in PARAMS[p]]
        for month in NOTICE_MONTHS:
            eff = dt.date(2026, month, 1)
            picked: List[Tuple[str, str, str]] = []
            amended = [k for k in keys if self.changes.get(k)]
            while len(picked) < 7:
                pool = amended if (amended and rng.random() < 0.45) else keys   # chains: re-amend something already amended
                k = rng.choice(pool)
                if k in picked:
                    continue
                prog, line, param = k
                old = self.value(prog, line, param, eff)
                new = old
                for _ in range(12):
                    cand = self._step(rng, PARAMS[prog][param][0], old)
                    if cand != old and self._valid(prog, line, param, cand, eff):
                        new = cand
                        break
                if new == old:
                    continue
                prev = self.changes.get(k, [])
                item = {"kind": "amend", "month": month, "effective": eff, "prog": prog, "line": line, "param": param, "old": old, "new": new,
                        "prev_notice": (prev[-1]["month"], prev[-1]["item_no"]) if prev else None}
                picked.append(k)
                self.changes.setdefault(k, []).append(item)
                self.notices[month].append(item)
            for pr in PROMOS:
                if pr["notice"] == month:
                    self.notices[month].append({"kind": "promo", "month": month, "effective": eff, "promo": pr})
                if pr["ext"] and pr["ext"][0] == month:
                    self.notices[month].append({"kind": "promo_ext", "month": month, "effective": eff, "promo": pr})
                if not pr["ext"] and pr["end"].month + 1 == month:
                    self.notices[month].append({"kind": "promo_end", "month": month, "effective": eff, "promo": pr})
            if month == 7:
                self.notices[month].append({"kind": "clawback", "month": month, "effective": eff, "lines": list(CLAWBACK_PRORATA)})
            rng.shuffle(self.notices[month])
            for n, it in enumerate(self.notices[month], 1):
                it["item_no"] = n
            earlier = [it for m in NOTICE_MONTHS if m < month for it in self.notices[m] if it["kind"] == "amend"
                       and self.changes[(it["prog"], it["line"], it["param"])][-1] is it]
            keep = rng.sample(earlier, k=min(2, len(earlier))) if earlier else []
            self.notices[month].append({"kind": "keep", "month": month, "effective": eff, "items": [(k["month"], k["item_no"]) for k in keep],
                                        "item_no": len(self.notices[month]) + 1})

    def promo_add(self, line: str, on: dt.date) -> int:
        return sum(p["add"] for p in PROMOS if p["line"] == line and p["start"] <= on <= self.promo_end(p))

    @staticmethod
    def promo_end(p: Dict[str, Any]) -> dt.date:
        return p["ext"][1] if p["ext"] else p["end"]


