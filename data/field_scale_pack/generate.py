def trail(L: Ledger, prog: str, line: str, param: str, on: dt.date, lang: str) -> str:
    unit = PARAMS[prog][param][0]
    hist = [h for h in L.history(prog, line, param) if h[0] <= on]
    return " → ".join(f"{fmt(unit, v, lang)} ({src}, {eff})" for eff, v, src in hist)


